"""Identifiers the de-identifier must never rename.

Renaming a name that a system header owns produces code that does not compile —
`memcpy` renamed to `nubvax` is an implicit-function-declaration error, a renamed
`st_size` is "no member named", a renamed `size_t` is a parse error. The compile
gate in `verify.py` is what actually catches an omission from this list, so treat
the list as an optimisation for the common case and the compiler as the authority.
A recipe adds target-specific names through `deidentify.reserved_extra`.

Anything matching `^_` or containing `__` is also left alone in `deidentify.py`:
those are reserved to the implementation in C, so a project identifier that looks
like one is not worth the risk of renaming.
"""

